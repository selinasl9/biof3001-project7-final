#!/usr/bin/env python3
"""BIOF3001 Project 7 — Mosquito RNA Virome.

Script: filter_hits_three_thresholds.py
Responsible contributor: [Confirm name before submission]

Objective
---------
Apply three alternative similarity-based filters to one-best-hit-per-contig
DIAMOND BLASTx annotations. These are exploratory candidate-screening branches;
they are NOT applied sequentially.

Input (generated by make_full_summary.py)
-----------------------------------------
results/summary/all_best_hits_with_metadata.tsv

Outputs
-------
results/viral_identification/filtered/strict_filtered_hits.tsv
results/viral_identification/filtered/loose_filtered_hits.tsv
results/viral_identification/filtered/evalue_filtered_hits.tsv

Criteria
--------
strict: pident >= 70 AND (query coverage >= 80 OR subject coverage >= 80)
loose : pident >= 30 AND (query coverage >= 50 OR subject coverage >= 50)
evalue: evalue < 1e-5

Coverage is calculated from query/subject alignment coordinates and the
corresponding full sequence lengths recorded by DIAMOND. For BLASTx, query
coordinates are nucleotide positions and subject coordinates are amino acid
positions, so each coverage fraction uses the appropriate length units.

Dependencies: Python 3 and pandas.
Run from any directory: python scripts/viral_identification/filter_hits_three_thresholds.py
"""

from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
INPUT = ROOT / "results/summary/all_best_hits_with_metadata.tsv"
OUTDIR = ROOT / "results/viral_identification/filtered"

REQUIRED = {
    "sample", "qseqid", "sscinames", "pident", "qstart", "qend",
    "sstart", "send", "qlen", "slen", "evalue",
}
NUMERIC = ["pident", "qstart", "qend", "sstart", "send", "qlen", "slen", "evalue"]


def main():
    if not INPUT.is_file():
        raise FileNotFoundError(f"Missing input: {INPUT}")

    df = pd.read_csv(INPUT, sep="\t")
    missing = REQUIRED - set(df.columns)
    if missing:
        raise ValueError(f"Missing columns in {INPUT}: {', '.join(sorted(missing))}")

    for col in NUMERIC:
        df[col] = pd.to_numeric(df[col], errors="coerce")

    # Invalid or zero lengths do not provide meaningful coverage.
    df["query_aligned_span"] = (df["qend"] - df["qstart"]).abs() + 1
    df["subject_aligned_span"] = (df["send"] - df["sstart"]).abs() + 1
    df["query_coverage_calc"] = (
        df["query_aligned_span"] / df["qlen"].where(df["qlen"] > 0) * 100
    )
    df["subject_coverage_calc"] = (
        df["subject_aligned_span"] / df["slen"].where(df["slen"] > 0) * 100
    )

    strict = df[
        (df["pident"] >= 70)
        & ((df["query_coverage_calc"] >= 80) | (df["subject_coverage_calc"] >= 80))
    ].copy()
    loose = df[
        (df["pident"] >= 30)
        & ((df["query_coverage_calc"] >= 50) | (df["subject_coverage_calc"] >= 50))
    ].copy()
    evalue_only = df[df["evalue"] < 1e-5].copy()

    OUTDIR.mkdir(parents=True, exist_ok=True)
    for mode, result in [("strict", strict), ("loose", loose), ("evalue", evalue_only)]:
        filename = OUTDIR / f"{mode}_filtered_hits.tsv"
        result.to_csv(filename, sep="\t", index=False)
        print(
            f"{mode.upper()}: {len(result)} hits, "
            f"{result['sample'].nunique()} runs, "
            f"{result['sscinames'].nunique()} reference scientific names -> {filename}"
        )
    print(f"Original best-hit rows: {len(df)}")
    print("Filtering finished; branches are alternatives, not sequential filters.")


if __name__ == "__main__":
    main()
